const MESSAGES: Readonly<Record<SupportedLanguage, Partial<Record<EnglishMessageKey, string>>>> = {
  en: EN_MESSAGES,
  it: IT_MESSAGES,
  de: DE_MESSAGES,
  es: ES_MESSAGES,
  fr: FR_MESSAGES,
};

/** Stable localization key for current user-facing presentation messages. */
export type MessageKey = EnglishMessageKey;

/** Ordered list of every message key currently known to the catalog. */
export const MESSAGE_KEYS = Object.keys(EN_MESSAGES) as readonly MessageKey[];

/**
 * Translates one presentation message, falling back to English deterministically.
 *
 * @example
 * translate("it", "event.goal")
 */
export function translate(
  language: SupportedLanguage = DEFAULT_LANGUAGE,
  key: MessageKey,
  variables: MessageVariables = {},
): string {
  const fallbackMessage = EN_MESSAGES[key];

  if (fallbackMessage === undefined) {
    throw new Error(`Unknown localization key: ${key}`);
  }

  const message = MESSAGES[language][key] ?? MESSAGES[FALLBACK_LANGUAGE][key] ?? fallbackMessage;
  return interpolate(message, variables);
}

/**
 * Creates a small fixed-language translator for presentation formatting code.
 */
export function createTranslator(language: SupportedLanguage = DEFAULT_LANGUAGE): Translator {
  return (key, variables = {}) => translate(language, key, variables);
}

/** Fixed-language translation function used by CLI and future UI adapters. */
export type Translator = (key: MessageKey, variables?: MessageVariables) => string;

/**
 * Reports whether a non-English language has a concrete translation for a key.
 */
export function hasConcreteTranslation(language: SupportedLanguage, key: MessageKey): boolean {
  return MESSAGES[language][key] !== undefined;
}

/**
 * Lists missing translation keys for a language.
 */
export function missingTranslationsFor(language: SupportedLanguage): readonly MessageKey[] {
  const missing: MessageKey[] = [];

  for (const key of MESSAGE_KEYS) {
    if (MESSAGES[language][key] === undefined) {
      missing.push(key);
    }
  }

  return missing;
}

/**
 * Replaces `{name}` placeholders with deterministic stringified variables.
 */
function interpolate(message: string, variables: MessageVariables): string {
  return message.replace(/\{([A-Za-z0-9_.-]+)\}/g, (placeholder, name: string) => {
    const value = variables[name];

    if (value === undefined) {
      return placeholder;
    }

    return String(value);
  });
}
